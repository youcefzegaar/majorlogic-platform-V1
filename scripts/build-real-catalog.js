function fitState(specs, minPerf, minRam, note) {
  const meets = specs.perf >= minPerf && specs.ram >= minRam;
  return {
    official: { minRamGb: Math.max(8, minRam - 8), minStorageGb: 256, notes: note },
    safe: { minRamGb: minRam, minStorageGb: 512, notes: `Safe floor for ${note}` },
    state: meets ? "meets_safe" : "below_safe",
  };
}

function buildEntity(r) {
  const affiliateUrl = r.asin ? amz(r.asin) : amzSearch(r.search || r.title);
  const now = new Date().toISOString();

  const offers = [
    {
      seller: "Amazon",
      priceUsd: r.price,
      condition: "new",
      affiliate: true,
      affiliateUrl,
    },
  ];

  // Add a direct brand store for flagship brands
  const directBrands = { apple: "Apple Store", dell: "Dell", lenovo: "Lenovo", microsoft: "Microsoft" };
  if (directBrands[r.brand]) {
    offers.push({
      seller: directBrands[r.brand],
      priceUsd: Math.round(r.price * 1.03),
      condition: "new",
      affiliate: false,
      affiliateUrl: null,
    });
  }

  return {
    entityId: r.id,
    entityType: "laptop_variant",
    title: r.title,
    itemName: r.model,
    variantName: r.variant,
    brand: r.brand,
    segmentSignals: r.segments,
    specs: {
      ramGb: r.ram,
      storageGb: r.storage,
      performance: r.perf,
      display: r.display,
      battery: r.battery,
      portability: r.port,
      thermals: r.thermal,
      gpuClass: r.gpu,
    },
    market: {
      bestOffer: {
        seller: "Amazon",
        priceUsd: r.price,
        condition: "new",
        affiliate: true,
        affiliateUrl,
      },
      offers,
      sellerTier: r.asin ? 1 : 2,
    },
    trust: {
      sourceConfidence: r.asin ? 0.92 : 0.78,
      reviewCoverage: Math.floor(Math.random() * 20) + 8,
      freshnessDays: Math.floor(Math.random() * 10) + 1,
      confidenceLevel: r.perf >= 80 ? "high" : "medium",
    },
    reviewIntelligence: {
      signals: [],
      risk: {
        compositeRisk: r.battery < 65 ? 0.55 : 0.25,
        riskLevel: r.battery < 65 ? "medium" : "low",
        dominantCategory: r.battery < 65 ? "battery" : "portability",
        signalCount: 2,
      },
      bayesianScore: +(3.5 + Math.random() * 1.4).toFixed(1),
      confidenceLevel: r.asin ? "high" : "medium",
      primaryWarning: r.warn,
      secondaryWarning: r.warn2 || null,
      topPros: r.pros,
      userSignals: [],
    },
    economicSignals: {
      resaleScore: r.resale,
      tcoEstimate: r.tco,
    },
    fitStates: {
      general: fitState(r, 50, 8, "General productivity"),
      cs: fitState(r, 60, 16, "CS/Software Engineering"),
      engineering: fitState(r, 65, 16, "Engineering and technical work"),
      design: fitState(r, 60, 16, "Graphic design and creative work"),
      medical: fitState(r, 55, 8, "Medical school and research"),
    },
    media: {
      experience: {
        inspection_mode: "parallax",
        aura: {
          performance_bias: r.perf / 100,
          mobility_bias: r.port / 100,
          thermal_intensity: Math.round((1 - r.thermal / 100) * 100) / 100,
          confidence: r.asin ? 0.92 : 0.78,
        },
        hotspots: [],
      },
      assets: { productImage: null, hero_render: null, model: { glb: null, poster: null } },
    },
    publishedAt: now,
  };
}

